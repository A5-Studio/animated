"""Turn the word-timed transcript of public/source.mp4 into caption chunks.

usage: python3 scripts/captions.py scripts/transcript.json src/captions.ts
"""
import json, re, sys

words = [w for seg in json.load(open(sys.argv[1])) for w in seg['words']]
toks = []
for w in words:
    t = w['w'].strip()
    if toks and (t.startswith('-') or t.startswith(',')):
        toks[-1]['t'] += t
        toks[-1]['e'] = w['e']
    else:
        toks.append({'t': t, 's': w['s'], 'e': w['e']})

# whisper mishearings -> what was said (matched on the bare word, punctuation kept)
core = lambda t: re.sub(r'[^\w]', '', t['t'])
i = 0
while i < len(toks):
    w = core(toks[i])
    nxt = core(toks[i + 1]) if i + 1 < len(toks) else ''
    if w == 'M' and nxt == 'arti':  # "M arti" = MRT
        toks[i]['t'] = 'MRT'; toks[i]['e'] = toks[i + 1]['e']; del toks[i + 1]
    elif w == 'blok':
        toks[i]['t'] = toks[i]['t'].replace('blok', 'Blok')
    elif w == 'Axe':
        toks[i]['t'] = 'Ask'
    elif w == 'macam':
        toks[i]['t'] = 'matcha'
    elif w == 'prom':
        toks[i]['t'] = 'prompt'
    elif w == 'you' and i == len(toks) - 1:
        toks[i]['t'] = 'you!'
    i += 1

# split at punctuation, then cut each phrase into balanced pieces of <= MAXC chars
MAXC = 20
phrases, cur = [], []
for t in toks:
    cur.append(t)
    if re.search(r'[.,!?]$', t['t']):
        phrases.append(cur); cur = []
if cur: phrases.append(cur)

L = lambda ws: len(' '.join(x['t'] for x in ws))
chunks = []
for ph in phrases:
    n = max(1, -(-L(ph) // MAXC))
    target = L(ph) / n
    piece = []
    for t in ph:
        if piece and L(piece + [t]) > target + 4 and len(chunks) >= 0 and L(ph[ph.index(t):]) > 6:
            chunks.append(piece); piece = []
        piece.append(t)
    chunks.append(piece)

out = []
for k, c in enumerate(chunks):
    a = c[0]['s']
    nxt = chunks[k + 1][0]['s'] if k + 1 < len(chunks) else c[-1]['e'] + 0.4
    b = min(nxt, c[-1]['e'] + 0.5)
    out.append((round(a, 2), round(b, 2), ' '.join(x['t'] for x in c)))

with open(sys.argv[2], 'w') as f:
    f.write('// generated by scripts/captions.py: [from, to, text] in seconds of public/source.mp4\n')
    f.write('export const CAPTIONS: [number, number, string][] = [\n')
    for a, b, t in out:
        f.write(f'  [{a}, {b}, {json.dumps(t, ensure_ascii=False)}],\n')
    f.write('];\n')
print(len(out), 'chunks')
for a, b, t in out: print(f'{a:6.2f} {b:6.2f} {t}')
