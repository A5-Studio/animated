"""Turn a faster-whisper word transcript into short caption pills (AI An Info standard:
at most ~20 characters per pill, split at punctuation and pauses).

Usage: python3 scripts/captions.py transcript.json src/captions.ts
"""
import json, re, sys

# misheard names and words -> what was said
FIX = {
    r'\bCloud\b': 'Claude', r'\bcloud\b': 'Claude', r'\bClaud\b': 'Claude', r'\bBluel\b': 'Beliau', r'\bBlue\b': 'Beliau', r'\bBluey\b': 'Beliau', r'\bBluyo\b': 'Beliau',
    r'\bTSEUS\b': 'Theseus', r'\bDreams\b': 'Trims', r'\bantropik\b': 'Anthropic', r'\bAntropik\b': 'Anthropic',
    r'\bbinar\b': 'biner', r'\bmemakili\b': 'mewakili', r'\bberfikir\b': 'berpikir', r'\bsejaman\b': 'sezaman',
    r'\bmengkonsep\b': 'mengonsep', r'\bpenyataan\b': 'pernyataan', r'\bdi Imitation\b': 'The Imitation',
    r'\bbergantikan\b': 'berganti', r'\bberistirahat berpikir\b': 'bisa berpikir', r'\bketinggalin\b': 'tinggalin',
    r'\bketinggalan\b': 'tinggalin', r'\bproject\b': 'proyek', r'\bSebenernya\b': 'Sebenarnya', r'\bYah\b': 'Ya',
    r'\bnom\b': '0', r'\bmemaklili\b': 'mewakili', r'\bTeseo\b': 'Theseus', r'\bberbicara\b': 'bisa',
    r'\btepat kerjanya\b': 'tempat kerjanya', r'\bAI model\b': 'AI modern', r'\bSilahkan\b': 'Silakan',
    r'\bTrims\.': 'Trims!',
}
MAX = 22

def fix(t):
    for a, b in FIX.items():
        t = re.sub(a, b, t)
    return t.replace(' -', '-').replace('- ', '-')

d = json.load(open(sys.argv[1]))
words = []
for seg in d:
    for w in seg['words']:
        # "1950 -an", "sama -sama": glue the suffix to its word so a pill never starts with "-"
        if words and w['w'].strip().startswith('-'):
            words[-1] = {**words[-1], 'w': words[-1]['w'] + w['w'].strip(), 'e': w['e']}
        else:
            words.append(dict(w))
caps, cur = [], []
for i, w in enumerate(words):
    cur.append(w)
    text = fix(' '.join(x['w'].strip() for x in cur))
    nxt = words[i + 1] if i + 1 < len(words) else None
    nxt_text = fix(' '.join(x['w'].strip() for x in cur + [nxt])) if nxt else ''
    punct = w['w'].strip()[-1:] in ',.?!'
    gap = nxt is not None and nxt['s'] - w['e'] > 0.22
    if punct or gap or nxt is None or len(nxt_text) > MAX:
        caps.append([round(cur[0]['s'], 2), round(w['e'], 2), text])
        cur = []
# mid-sentence "Beliau" after a comma reads as "beliau"
for i in range(1, len(caps)):
    if caps[i - 1][2].endswith(',') and caps[i][2].startswith('Beliau'):
        caps[i][2] = 'b' + caps[i][2][1:]
# hold each pill until the next one starts (no flicker on short gaps)
for i in range(len(caps) - 1):
    if caps[i + 1][0] - caps[i][1] < 0.35:
        caps[i][1] = caps[i + 1][0]
with open(sys.argv[2], 'w') as f:
    f.write('// generated by scripts/captions.py: [from, to, text] in seconds of public/source.mp4\n')
    f.write('export const CAPTIONS: [number, number, string][] = [\n')
    for a, b, t in caps:
        f.write(f'  [{a}, {b}, {json.dumps(t, ensure_ascii=False)}],\n')
    f.write('];\n')
print(len(caps), 'pills, longest', max(len(c[2]) for c in caps))
