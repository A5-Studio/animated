"""Turn the speech clip into data the video reads.

Usage:
  python3 scripts/prep_audio.py <speech.wav> <transcript.json|-> src/audio-data.ts
  python3 scripts/prep_audio.py --placeholder 30 src/audio-data.ts

Writes the per-frame voice level (drives the cartoon's mouth), the clip
length, and caption chunks of a few words with their start/end seconds.
transcript.json is faster-whisper output: [{"words": [{"w", "s", "e"}]}].
"""
import json
import math
import sys
import wave

import numpy as np

FPS = 30


def envelope(path):
    with wave.open(path) as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768
        if w.getnchannels() == 2:
            x = x.reshape(-1, 2).mean(1)
    hop = sr // FPS
    rms = np.array([math.sqrt(float(np.mean(x[i:i + hop] ** 2)) + 1e-12) for i in range(0, len(x) - hop, hop)])
    db = 20 * np.log10(rms)
    lvl = np.clip((db + 45) / 30, 0, 1)  # -45 dB silent .. -15 dB loud
    return lvl, len(x) / sr


def chunks(words, max_words=4, max_gap=0.5):
    out, cur = [], []
    for w in words:
        if cur and (len(cur) >= max_words or w['s'] - cur[-1]['e'] > max_gap):
            out.append(cur)
            cur = []
        cur.append(w)
    if cur:
        out.append(cur)
    return [{'a': round(c[0]['s'], 2), 'b': round(c[-1]['e'], 2), 't': ' '.join(x['w'].strip() for x in c)} for c in out]


if sys.argv[1] == '--placeholder':
    dur = float(sys.argv[2])
    n = int(dur * FPS)
    lvl = [round(max(0.0, math.sin(i * 0.9) * 0.5 + 0.4 * math.sin(i * 0.23)), 2) if (i // 45) % 4 != 3 else 0 for i in range(n)]
    caps = [{'a': i * 2.5, 'b': i * 2.5 + 2.3, 't': '(teks pidato menyusul)'} for i in range(int(dur // 2.5))]
    out = sys.argv[3]
else:
    wav, tr, out = sys.argv[1:4]
    lvl, dur = envelope(wav)
    lvl = [round(float(v), 2) for v in lvl]
    caps = []
    if tr != '-':
        words = [w for seg in json.load(open(tr)) for w in seg['words']]
        caps = chunks(words)

with open(out, 'w') as f:
    f.write('// Generated by scripts/prep_audio.py. Do not edit by hand.\n')
    f.write(f'export const AUDIO_SECONDS = {dur:.2f};\n')
    f.write(f'export const LEVEL: number[] = {json.dumps(lvl)};\n')
    f.write(f'export const CAPTIONS: {{ a: number; b: number; t: string }}[] = {json.dumps(caps, ensure_ascii=False)};\n')
print('wrote', out, f'{dur:.1f}s', len(caps), 'captions')
