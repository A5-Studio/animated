"""Word-by-word karaoke captions from a faster-whisper word transcript.

Groups of at most 3 words (or ~18 characters), broken at punctuation and pauses. Each word keeps
its own time, so the word being said gets the highlight box.
Usage: python3 scripts/karaoke.py transcript.json src/karaoke.ts
"""
import json, re, sys

FIX = {
    r'\bCloud\b': 'Claude', r'\bcloud\b': 'Claude', r'\bClaud\b': 'Claude', r'\bBluel\b': 'Beliau', r'\bBlue\b': 'Beliau', r'\bBluey\b': 'Beliau', r'\bBluyo\b': 'Beliau',
    r'\bTSEUS\b': 'Theseus', r'\bDreams\b': 'Trims', r'\bantropik\b': 'Anthropic', r'\bAntropik\b': 'Anthropic',
    r'\bbinar\b': 'biner', r'\bmemakili\b': 'mewakili', r'\bberfikir\b': 'berpikir', r'\bsejaman\b': 'sezaman',
    r'\bmengkonsep\b': 'mengonsep', r'\bpenyataan\b': 'pernyataan', r'\bdi Imitation\b': 'The Imitation',
    r'\bbergantikan\b': 'berganti', r'\bberistirahat berpikir\b': 'bisa berpikir', r'\bketinggalin\b': 'tinggalin',
    r'\bketinggalan\b': 'tinggalin', r'\bproject\b': 'proyek', r'\bSebenernya\b': 'Sebenarnya', r'\bYah\b': 'Ya',
    r'\bnom\b': '0', r'\bmemaklili\b': 'mewakili', r'\bTeseo\b': 'Theseus', r'\bberbicara\b': 'bisa',
    r'\btepat kerjanya\b': 'tempat kerjanya', r'\bAI model\b': 'AI modern', r'\bSilahkan\b': 'Silakan',
    r'\bTrims\.': 'Trims!',
}
MAX_WORDS, MAX_CHARS = 3, 18

def fix(t):
    for a, b in FIX.items():
        t = re.sub(a, b, t)
    return t

d = json.load(open(sys.argv[1]))
words = []
for seg in d:
    for w in seg['words']:
        if words and w['w'].strip().startswith('-'):
            words[-1] = {**words[-1], 'w': words[-1]['w'] + w['w'].strip(), 'e': w['e']}
        else:
            words.append(dict(w))
# fixes that span two words ("di Imitation", "AI model", "tepat kerjanya", "beristirahat berpikir") are applied on pairs
toks = [w['w'].strip() for w in words]
for i in range(len(toks) - 1):
    pair = fix(toks[i] + ' ' + toks[i + 1])
    if pair != toks[i] + ' ' + toks[i + 1] and ' ' in pair:
        a, b = pair.split(' ', 1)
        toks[i], toks[i + 1] = a, b
toks = [fix(t) for t in toks]
groups, cur = [], []
for i, w in enumerate(words):
    cur.append([toks[i], round(w['s'], 2), round(w['e'], 2)])
    nxt = words[i + 1] if i + 1 < len(words) else None
    text = ' '.join(c[0] for c in cur)
    nxt_len = len(text) + 1 + len(toks[i + 1]) if nxt else 0
    punct = toks[i][-1:] in ',.?!'
    gap = nxt is not None and nxt['s'] - w['e'] > 0.22
    if punct or gap or nxt is None or len(cur) >= MAX_WORDS or nxt_len > MAX_CHARS:
        groups.append(cur)
        cur = []
# strip trailing commas/periods from the shown words (the reference shows bare words), keep ?!
for g in groups:
    for c in g:
        c[0] = c[0].rstrip(',.')
with open(sys.argv[2], 'w') as f:
    f.write('// generated by scripts/karaoke.py: groups of [word, from, to] in seconds of public/source.mp4\n')
    f.write('export const KARAOKE: [string, number, number][][] = [\n')
    for g in groups:
        f.write('  [' + ', '.join(f'[{json.dumps(c[0], ensure_ascii=False)}, {c[1]}, {c[2]}]' for c in g) + '],\n')
    f.write('];\n')
print(len(groups), 'groups')
