"""Join VO parts into public/vo.wav (-14 LUFS) and write src/timing.ts.

usage: python3 scripts/build_vo.py id1=part1.wav id2=part2.wav ...

- 0.3 s of silence before the first part, GAP (default 0.3 s) between parts,
  TAIL (default 2.2 s) after the last one so the comment CTA can breathe
- two-pass ffmpeg loudnorm to -14 LUFS / -1 dBTP
- word timestamps from faster-whisper (medium, Indonesian), tagged per part
"""
import json, os, subprocess, sys, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SR = 48000
LEAD, GAP, TAIL = 0.3, float(os.environ.get("GAP", "0.3")), float(os.environ.get("TAIL", "2.2"))


def load(p):
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", p, "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768


def trim(a, thr=0.012):
    idx = np.where(np.abs(a) > thr)[0]
    if not len(idx):
        return a
    pad = int(0.04 * SR)
    return a[max(0, idx[0] - pad): idx[-1] + pad]


ids, paths = zip(*(arg.split("=", 1) for arg in sys.argv[1:]))
parts = [trim(load(p)) for p in paths]
out, spans, t = [np.zeros(int(LEAD * SR), np.float32)], [], LEAD
for i, a in enumerate(parts):
    spans.append((t, t + len(a) / SR))
    out.append(a)
    t += len(a) / SR
    gap = GAP if i + 1 < len(parts) else TAIL
    out.append(np.zeros(int(gap * SR), np.float32))
    t += gap
mix = np.concatenate(out)
raw_path = os.path.join(ROOT, "public", "vo_raw.wav")
with wave.open(raw_path, "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((np.clip(mix, -1, 1) * 32767).astype(np.int16).tobytes())

target = "I=-14:TP=-1:LRA=11"
r = subprocess.run(["ffmpeg", "-hide_banner", "-i", raw_path, "-af", f"loudnorm={target}:print_format=json", "-f", "null", "-"], capture_output=True, text=True)
m = json.loads(r.stderr[r.stderr.rindex("{"): r.stderr.rindex("}") + 1])
af = (f"loudnorm={target}:measured_I={m['input_i']}:measured_TP={m['input_tp']}:measured_LRA={m['input_lra']}"
      f":measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
vo_path = os.path.join(ROOT, "public", "vo.wav")
subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", raw_path, "-af", af, "-ar", str(SR), "-ac", "1", vo_path], check=True)
os.remove(raw_path)

from faster_whisper import WhisperModel
model = WhisperModel("medium", device="cpu", compute_type="int8")
a16 = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", vo_path, "-ac", "1", "-ar", "16000", "-f", "s16le", "-"], capture_output=True, check=True).stdout
a16 = np.frombuffer(a16, dtype=np.int16).astype(np.float32) / 32768
segs, _ = model.transcribe(a16, language="id", word_timestamps=True, beam_size=5)
words = []
for sg in segs:
    for w in sg.words:
        mid = (w.start + w.end) / 2
        p = next((i for i, (a, b) in enumerate(spans) if a - 0.2 <= mid <= b + 0.2), None)
        if p is not None:
            words.append({"w": w.word.strip(), "s": round(w.start, 3), "e": round(w.end, 3), "p": ids[p]})

with open(os.path.join(ROOT, "src", "timing.ts"), "w") as fh:
    fh.write("// Generated by scripts/build_vo.py. Do not edit by hand.\n")
    fh.write(f"export const TOTAL_SEC = {t:.3f};\n")
    fh.write("export const PARTS: Record<string, { s: number; e: number }> = " + json.dumps({k: {"s": round(a, 3), "e": round(b, 3)} for k, (a, b) in zip(ids, spans)}) + ";\n")
    fh.write("export const WORDS: { w: string; s: number; e: number; p: string }[] = " + json.dumps(words, ensure_ascii=False) + ";\n")
print(f"vo.wav {t:.2f}s, {len(words)} words")
